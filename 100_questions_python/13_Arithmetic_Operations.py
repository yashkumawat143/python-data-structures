# Calculate addition, subtraction, multiplication, division, floor division, modulus, and exponentiation of two numbers.
n1=int(input("Enter the first number : "));
n2=int(input("Enter the second number : "));
print("----sum----");
print(n1+n2);
print("----subtraction----");
print(n1-n2);
print("----multiplication----");
print(n1*n2);
print("----division----");
print(n1//n2);
print("----modulus----");
print(n1%n2);
print("----exponentiation----");
print(n1**n2);
